export interface PeriodTiming {
  startTime: string;
  endTime: string;
}

export type SubjectCategory = 'Core' | 'Language' | 'Other';

export interface BatchSubject {
  subject: string;
  count: number;
  category?: SubjectCategory;
}

export interface Faculty {
  id: string;
  name: string;
  subjects: string[];
  maxPeriodsPerDay?: number;
  isAbsent?: boolean; // Legacy global flag for backward compatibility
  absentDays?: DayOfWeek[]; // Per-day absence list (M3)
  assignedBatches?: string[]; // Exclusive batch IDs; empty/undefined = unrestricted
  unavailableDates?: string[]; // Date-specific unavailability (YYYY-MM-DD or DayOfWeek)
  unavailablePeriods?: { day?: DayOfWeek; date?: string; periodIndex: number }[];
}

export const WEEKDAYS = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'] as const;
export const ALL_DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'] as const;
export type Weekday = typeof WEEKDAYS[number];
export type DayOfWeek = typeof ALL_DAYS[number];

export interface Batch {
  id: string;
  building: string;
  yearCategory: string;
  name: string;
  roomNumber: string;
  periods: PeriodTiming[];
  subjects: BatchSubject[];
}

export type TimetableStatus = 'Draft' | 'Finalized' | 'Archived';

export interface Allocation {
  batchId: string;
  periodIndex: number;
  facultyId: string;
  subject: string;
  autoGenerated?: boolean;
  manualEdited?: boolean;
  frozen?: boolean;
  explanation?: string[];
  vacatedFacultyId?: string;   // set when the original faculty went absent after generation
  vacatedFacultyName?: string; // cached name, preserved if faculty is deleted
  subjectChanged?: boolean;    // H4: true when absence patching changed subject from original
  updatedAt?: number;
  hasConflictOverride?: boolean; // true if saved despite a non-blocking or confirmed conflict
  overridden?: boolean; // true if manual override bypassed hard constraints (C2)
  conflictNote?: string;
}

export interface FrozenViolation {
  allocation: Allocation;
  batchId: string;
  periodIndex: number;
  facultyId?: string;
  reason: string;
  type: 'ABSENT' | 'TIME_OVERLAP' | 'MAX_LOAD' | 'FACULTY_NOT_FOUND' | 'BATCH_NOT_FOUND' | 'BATCH_RESTRICTION' | 'ROOM_OVERLAP';
}

export interface Timetable {
  id: string;
  date: string; // DayOfWeek or YYYY-MM-DD
  status: TimetableStatus;
  allocations: Allocation[];
  lastGeneratedAt?: number;
  updatedAt?: number;
  unfilledSlots?: UnfilledSlot[];
  warnings?: ScheduleWarning[];
  frozenViolations?: FrozenViolation[];
  stats?: GenerationStats;
  seed?: number;
}

export interface SchedulerSettings {
  pcmbWeight: number;
  languageWeight: number;
  maxDailyPeriods: number;
  weekStartDay: DayOfWeek;
  enableGapOptimization: boolean;
  enableConsecutivePeriodAvoidance: boolean;
  enableStrictPeriod1NoLanguage?: boolean;
  enableKHSGrouping?: boolean;
  respectDailyLimits?: boolean;
  allowSameSubjectConsecutive?: boolean;
  randomSeed?: number;
  subjectCategories?: Record<string, SubjectCategory>;
}

export type AuditLogAction =
  | 'MANUAL_OVERRIDE'
  | 'FREEZE_TOGGLE'
  | 'STATUS_CHANGE'
  | 'TIMETABLE_GENERATE'
  | 'ABSENCE_SYNC'
  | 'SLOT_REGENERATE'
  | 'BATCH_REGENERATE'
  | 'FACULTY_CREATE'
  | 'FACULTY_UPDATE'
  | 'FACULTY_DELETE'
  | 'FACULTY_MERGE'
  | 'BATCH_CREATE'
  | 'BATCH_UPDATE'
  | 'BATCH_DELETE'
  | 'BACKUP_EXPORT'
  | 'BACKUP_RESTORE'
  | 'SETTINGS_UPDATE';

export interface AuditLog {
  id: string;
  timestamp: number;
  action: AuditLogAction;
  batchId?: string;
  periodIndex?: number;
  previousFacultyId?: string;
  newFacultyId?: string;
  reason?: string;
  day?: DayOfWeek;
}

export type UnfilledReason =
  | 'NO_QUALIFIED_TEACHER'
  | 'ALL_BUSY'
  | 'DAILY_LIMIT'
  | 'ALL_ABSENT'
  | 'NO_SUBJECTS';

export interface UnfilledSlot {
  batchId: string;
  batchName: string;
  periodIndex: number;
  requiredSubject?: string;
  reason: UnfilledReason | string;
  candidateIssue?: string;
}

export interface GenerationStats {
  totalSlots: number;
  filledSlots: number;
  unfilledSlots: number;
  fillPercentage: number;
  period1LanguageCount: number;
  byPeriodFilled: Record<number, number>;
  repairedSlotsCount: number;
}

export interface ScheduleWarning {
  type:
    | 'PERIOD_1_LANGUAGE'
    | 'WORKLOAD_CAP'
    | 'CONSECUTIVE_OVERUSE'
    | 'ABSENCE_GAP'
    | 'ROOM_CONFLICT'
    | 'UNFILLED_SLOT'
    | 'QUOTA_DEFICIT';
  message: string;
  batchId?: string;
  periodIndex?: number;
  facultyId?: string;
  severity: 'warning' | 'error' | 'info';
}

export interface GenerationResult {
  allocations: Allocation[];
  unfilled: UnfilledSlot[];
  warnings: ScheduleWarning[];
  stats: GenerationStats;
  frozenViolations?: FrozenViolation[];
  score?: number;
  seed?: number;
}

export interface SubstituteCandidate {
  faculty: Faculty;
  score: number;
  eligible: boolean;
  reasons: string[];
  currentDayLoad: number;
  maxDayLoad: number;
}

export interface SubjectCapacityReport {
  subject: string;
  category: SubjectCategory;
  requiredWeeklyPeriods: number;
  availableWeeklyPeriods: number;
  deficit: number;
  facultyCount: number;
  qualifiedFacultyNames: string[];
  status: 'surplus' | 'balanced' | 'deficit';
}

export interface ConflictCheckResult {
  hasConflict: boolean;
  type?: 'TIME_OVERLAP' | 'MAX_LOAD' | 'ABSENT' | 'BATCH_RESTRICTION' | 'ROOM_OVERLAP' | 'DATE_UNAVAILABLE';
  message: string | null;
  severity?: 'hard_error' | 'soft_warning';
  conflictingBatchName?: string;
  conflictingPeriod?: number;
}

export interface BackupData {
  version: number;
  exportedAt: number;
  faculty: Faculty[];
  batches: Batch[];
  settings: SchedulerSettings;
  weekTimetables: Partial<Record<DayOfWeek, Timetable>>;
  dateAbsences?: Record<string, string[]>;
  auditLogs: AuditLog[];
}
