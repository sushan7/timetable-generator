import { describe, it, expect, beforeEach } from 'vitest';
import type { Batch, Allocation, Faculty } from '../types';
import { buildTimetableWorkbook, buildTimetablePdf } from '../utils/export';
import { calculateTimetableQuota } from '../hooks/useTimetableQuota';
import { storage } from '../utils/storage';

describe('Exports & Refactored Utilities (M9, L5)', () => {
  const sampleBatches: Batch[] = [
    {
      id: 'batch-1',
      name: 'Lakshya 10',
      building: 'Building 1',
      roomNumber: '101',
      yearCategory: 'First PU',
      subjects: [{ subject: 'Physics', count: 4, category: 'Core' }],
      periods: [
        { startTime: '08:30', endTime: '09:30' },
        { startTime: '09:30', endTime: '10:30' },
        { startTime: '10:45', endTime: '11:45' },
        { startTime: '11:45', endTime: '12:45' },
      ], // 4 periods, demonstrating dynamic period counts (not hard-coded 6)
    },
    {
      id: 'batch-2',
      name: 'Prerana 20',
      building: 'Building 2',
      roomNumber: '202',
      yearCategory: 'Second PU',
      subjects: [{ subject: 'Chemistry', count: 4, category: 'Core' }],
      periods: [
        { startTime: '08:00', endTime: '09:00' },
        { startTime: '09:00', endTime: '10:00' },
        { startTime: '10:15', endTime: '11:15' },
      ], // 3 periods
    },
  ];

  const sampleFaculties: Faculty[] = [
    {
      id: 'fac-1',
      name: 'Dr. Jane Smith',
      subjects: ['Physics'],
      maxPeriodsPerDay: 4,
      isAbsent: false,
    },
    {
      id: 'fac-2',
      name: 'Prof. John Doe',
      subjects: ['Chemistry'],
      maxPeriodsPerDay: 4,
      isAbsent: true,
      absentDays: ['Monday'],
    },
  ];

  const sampleAllocations: Allocation[] = [
    {
      batchId: 'batch-1',
      periodIndex: 0,
      facultyId: 'fac-1',
      subject: 'Physics',
      autoGenerated: true,
      frozen: true,
    },
    {
      batchId: 'batch-2',
      periodIndex: 0,
      facultyId: '',
      vacatedFacultyId: 'fac-2',
      vacatedFacultyName: 'Prof. John Doe',
      subject: 'Chemistry',
      autoGenerated: true,
    },
  ];

  beforeEach(() => {
    storage.initialize();
  });

  describe('Excel Export (Multi-Sheet per Section + Summary)', () => {
    it('creates workbook with Summary sheet and dedicated section sheets with dynamic periods', () => {
      const workbook = buildTimetableWorkbook(
        'Monday',
        sampleBatches,
        sampleAllocations,
        sampleFaculties,
        'Draft'
      );

      // 1. Verify Summary sheet
      const summary = workbook.getWorksheet('Summary');
      expect(summary).toBeDefined();

      // Check Summary Title banner
      const titleCell = summary?.getRow(1).getCell(1).value;
      expect(titleCell).toBe('TIMETABLE PRO — ACADEMIC SCHEDULE SUMMARY');

      // 2. Verify Section sheets exist
      // batch-1 is Building 1 First PU -> "B1 First PU"
      // batch-2 is Building 2 Second PU -> "B2 Second PU"
      const b1Sheet = workbook.getWorksheet('B1 First PU');
      expect(b1Sheet).toBeDefined();

      // Check real period count for batch-1: 4 periods
      // Columns: Building, Track, Batch Name, Room No, P1, P2, P3, P4
      expect(b1Sheet?.columns?.length).toBe(4 + 4);

      const b2Sheet = workbook.getWorksheet('B2 Second PU');
      expect(b2Sheet).toBeDefined();

      // Check real period count for batch-2: 3 periods
      // Columns: Building, Track, Batch Name, Room No, P1, P2, P3
      expect(b2Sheet?.columns?.length).toBe(4 + 3);
    });
  });

  describe('PDF Export (Real text & Section Pagination via jspdf-autotable)', () => {
    it('generates paginated vector PDF with real text across sections', () => {
      const doc = buildTimetablePdf(
        'Monday',
        sampleBatches,
        sampleAllocations,
        sampleFaculties,
        'Draft'
      );

      expect(doc).toBeDefined();
      // 2 sections active -> doc has 2 pages, one per section
      expect(doc.getNumberOfPages()).toBe(2);
    });
  });

  describe('Timetable Quota Calculation (Extracted Logic)', () => {
    it('accurately computes core science, language, gap count and absent faculty', () => {
      const result = calculateTimetableQuota('Monday', sampleAllocations, sampleFaculties);

      expect(result.gapCount).toBe(1); // 1 vacated gap
      expect(result.absentFacultyCount).toBe(1); // 1 absent teacher
      expect(result.quota).toBeDefined();
      expect(result.quota.pcmb).toBeGreaterThanOrEqual(1); // Physics is Core PCMB
    });
  });
});
