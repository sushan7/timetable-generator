import { describe, it, expect, beforeEach } from 'vitest';
import { initialBatches, initialFaculty } from '../utils/seedData';
import {
  generateTimetableV2,
  generateWeekTimetables,
  patchAbsences,
} from '../utils/scheduler';
import { canAssign } from '../utils/constraints';
import { parseTimeMinutesStrict, isOverlapping } from '../utils/validation';
import { storage, compactAllocation, safeStorage, KEYS } from '../utils/storage';
import type { Allocation, DayOfWeek, Faculty, WeekTimetables } from '../types';

const WEEKDAYS: DayOfWeek[] = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
const CORE_SUBJECTS = ['Physics', 'Chemistry', 'Mathematics', 'Biology'];
const LANGUAGE_SUBJECTS = ['English', 'Kannada', 'Hindi', 'Sanskrit', 'Second Language'];

describe('Prompt 11 Suite: Complete Invariants, Storage Size Reduction & Verification (L4, T1)', () => {
  beforeEach(() => {
    safeStorage.clear();
    storage.initialize();
  });

  describe('L4: Storage Footprint Reduction & Allocation Compaction', () => {
    it('compactAllocation preserves critical metadata and strips verbose debug explanations', () => {
      const verboseAlloc: Allocation = {
        batchId: 'batch_test_1',
        periodIndex: 0,
        facultyId: 'fac_test_1',
        subject: 'Physics',
        autoGenerated: true,
        explanation: [
          'Detailed debug reason 1: candidate qualified and available',
          'Detailed debug reason 2: teacher load balanced across building 1',
          'Detailed debug reason 3: travel gap between buildings respected',
        ],
      };

      const compacted = compactAllocation(verboseAlloc);
      expect(compacted.batchId).toBe('batch_test_1');
      expect(compacted.periodIndex).toBe(0);
      expect(compacted.facultyId).toBe('fac_test_1');
      expect(compacted.subject).toBe('Physics');
      // For vanilla auto-generated slot without conflicts or overrides, explanations are omitted
      expect(compacted.explanation).toBeUndefined();
    });

    it('compactAllocation keeps concise reason when slot has conflict override, manual edit or subject changed', () => {
      const changedAlloc: Allocation = {
        batchId: 'batch_test_2',
        periodIndex: 1,
        facultyId: 'fac_test_2',
        subject: 'Chemistry',
        subjectChanged: true,
        conflictNote: 'Replaced absent faculty with substitute',
        explanation: [
          'Subject changed from Physics to Chemistry because no qualified Physics teachers were available during this period.',
          'Extra verbose trace line 2',
        ],
      };

      const compacted = compactAllocation(changedAlloc);
      expect(compacted.subjectChanged).toBe(true);
      expect(compacted.conflictNote).toBe('Replaced absent faculty with substitute');
      expect(compacted.explanation).toBeDefined();
      expect(compacted.explanation?.length).toBe(1);
      expect(compacted.explanation?.[0]).toContain('Subject changed from Physics to Chemistry');
    });

    it('stores an entire 6-day week (2,232 slots) well under 1 MB in localStorage (< 500 KB)', () => {
      const weekResult = generateWeekTimetables(
        initialBatches,
        initialFaculty,
        {},
        storage.getSettings(),
        { seed: 12345 }
      );

      // Save via storage which automatically applies compactAllocation
      storage.setWeekTimetables(weekResult.weekTimetables);

      // Read raw serialized string from storage
      const rawStoredWeek = safeStorage.getItem(KEYS.WEEK);
      expect(rawStoredWeek).not.toBeNull();

      const byteLength = new TextEncoder().encode(rawStoredWeek!).length;
      const sizeInKb = byteLength / 1024;
      const sizeInMb = sizeInKb / 1024;

      // Assert total stored week is well under 1 MB (typically 250-400 KB)
      expect(sizeInMb).toBeLessThan(1.0);
      expect(sizeInKb).toBeLessThan(800); // Strict check: under 800 KB

      // Verify that after reading back, all 6 days and all 372 slots per day are intact
      const loadedWeek = storage.getWeekTimetables();
      WEEKDAYS.forEach(day => {
        expect(loadedWeek[day]?.allocations.length).toBe(372);
      });
    }, 30000);
  });

  describe('T1: Full 6-Day Invariants on Seed Data', () => {
    it('satisfies all 6-day invariants: 372/372 filled, 0 overlaps, 0 daily limit violations, and ZERO languages in Period 1 when teachers are plentiful', () => {
      const weekResult = generateWeekTimetables(
        initialBatches,
        initialFaculty,
        {},
        storage.getSettings(),
        { seed: 98765 }
      );

      let totalFilledSlots = 0;
      let totalTeacherOverlaps = 0;
      let totalDailyLimitViolations = 0;
      let period1LanguageCount = 0;

      for (const day of WEEKDAYS) {
        const dayTT = weekResult.weekTimetables[day];
        expect(dayTT).toBeDefined();
        const allocs = dayTT!.allocations;

        // Invariant 1: 372/372 slots filled for each day
        expect(allocs.length).toBe(372);
        totalFilledSlots += allocs.length;

        // Invariant 2: 0 teacher time overlaps on that day
        for (let i = 0; i < allocs.length; i++) {
          const a1 = allocs[i];
          const b1 = initialBatches.find(b => b.id === a1.batchId);
          const p1 = b1?.periods[a1.periodIndex];
          if (!p1 || !p1.startTime || !p1.endTime) continue;

          for (let j = i + 1; j < allocs.length; j++) {
            const a2 = allocs[j];
            if (a1.facultyId !== a2.facultyId) continue;

            const b2 = initialBatches.find(b => b.id === a2.batchId);
            const p2 = b2?.periods[a2.periodIndex];
            if (!p2 || !p2.startTime || !p2.endTime) continue;

            if (isOverlapping(p1.startTime, p1.endTime, p2.startTime, p2.endTime)) {
              totalTeacherOverlaps++;
            }
          }
        }

        // Invariant 3: 0 daily limit violations (no teacher assigned > max daily limit)
        const dailyTeacherCounts: Record<string, number> = {};
        allocs.forEach(a => {
          dailyTeacherCounts[a.facultyId] = (dailyTeacherCounts[a.facultyId] || 0) + 1;
        });

        for (const [facId, count] of Object.entries(dailyTeacherCounts)) {
          const fac = initialFaculty.find(f => f.id === facId);
          const limit = fac?.maxPeriodsPerDay || 4;
          if (count > limit) {
            totalDailyLimitViolations++;
          }
        }

        // Invariant 4: ZERO language in Period 1 when teachers are plentiful
        // On seed data, all batches have qualified teachers available for core PCMB subjects
        const period1Allocs = allocs.filter(a => a.periodIndex === 0);
        expect(period1Allocs.length).toBe(70); // All 70 batches have period 1

        period1Allocs.forEach(a => {
          if (LANGUAGE_SUBJECTS.includes(a.subject)) {
            period1LanguageCount++;
          }
          expect(CORE_SUBJECTS).toContain(a.subject);
        });
      }

      // Assert summary totals
      expect(totalFilledSlots).toBe(2232); // 372 * 6
      expect(totalTeacherOverlaps).toBe(0);
      expect(totalDailyLimitViolations).toBe(0);
      expect(period1LanguageCount).toBe(0); // ZERO language in Period 1
    }, 30000);

    it('respects frozen/locked slots across all days during generation', () => {
      // Pre-lock 3 specific slots in different days
      const existingWeek: WeekTimetables = {};

      // Lock Monday slot for batch 0
      const lockedMonday: Allocation = {
        batchId: initialBatches[0].id,
        periodIndex: 0,
        facultyId: 'fac_locked_mon',
        subject: 'Physics',
        frozen: true,
      };

      // Lock Wednesday slot for batch 1
      const lockedWednesday: Allocation = {
        batchId: initialBatches[1].id,
        periodIndex: 2,
        facultyId: 'fac_locked_wed',
        subject: 'Chemistry',
        frozen: true,
      };

      existingWeek['Monday'] = { id: 'tt_mon', date: 'Monday', status: 'Draft', allocations: [lockedMonday] };
      existingWeek['Wednesday'] = { id: 'tt_wed', date: 'Wednesday', status: 'Draft', allocations: [lockedWednesday] };

      const weekResult = generateWeekTimetables(
        initialBatches,
        initialFaculty,
        existingWeek,
        storage.getSettings(),
        { seed: 555 }
      );

      // Verify locked Monday slot was strictly preserved
      const monAlloc = weekResult.weekTimetables['Monday']?.allocations.find(
        a => a.batchId === lockedMonday.batchId && a.periodIndex === lockedMonday.periodIndex
      );
      expect(monAlloc?.facultyId).toBe('fac_locked_mon');
      expect(monAlloc?.frozen).toBe(true);

      // Verify locked Wednesday slot was strictly preserved
      const wedAlloc = weekResult.weekTimetables['Wednesday']?.allocations.find(
        a => a.batchId === lockedWednesday.batchId && a.periodIndex === lockedWednesday.periodIndex
      );
      expect(wedAlloc?.facultyId).toBe('fac_locked_wed');
      expect(wedAlloc?.frozen).toBe(true);
    }, 30000);

    it('produces 100% deterministic identical timetables for a fixed seed', () => {
      const run1 = generateTimetableV2(initialBatches, initialFaculty, [], [], { seed: 444333 });
      const run2 = generateTimetableV2(initialBatches, initialFaculty, [], [], { seed: 444333 });

      expect(run1.allocations.length).toBe(run2.allocations.length);
      for (let i = 0; i < run1.allocations.length; i++) {
        expect(run1.allocations[i].batchId).toBe(run2.allocations[i].batchId);
        expect(run1.allocations[i].periodIndex).toBe(run2.allocations[i].periodIndex);
        expect(run1.allocations[i].facultyId).toBe(run2.allocations[i].facultyId);
        expect(run1.allocations[i].subject).toBe(run2.allocations[i].subject);
      }
    });
  });

  describe('T1: Edge Cases, Migrations, Time Parsing & Constraints', () => {
    it('strict time parsing parseTimeMinutesStrict rejects out-of-range, non-normalized and invalid strings', () => {
      expect(parseTimeMinutesStrict('1:30')).toBe(90);
      expect(parseTimeMinutesStrict('01:30')).toBe(90);
      expect(parseTimeMinutesStrict('09:00 PM')).toBe(1260);
      expect(parseTimeMinutesStrict('25:99')).toBeNull();
      expect(parseTimeMinutesStrict('')).toBeNull();
      expect(parseTimeMinutesStrict('invalid text')).toBeNull();
      expect(parseTimeMinutesStrict('12:60')).toBeNull();
      expect(parseTimeMinutesStrict('24:00')).toBeNull();
    });

    it('canAssign rejects unavailable day/period and absent faculty as hard constraints', () => {
      const sampleBatch = initialBatches[0];
      const sampleFaculty: Faculty = {
        ...initialFaculty[0],
        unavailable: [{ day: 'Monday', periods: [0, 1] }],
        absentDays: ['Tuesday'],
      };

      // Monday Period 0: hard blocked because unavailable
      const unavailableCheck = canAssign(sampleFaculty, sampleBatch, 0, [], initialBatches, storage.getSettings(), {
        dayOfWeek: 'Monday',
      });
      expect(unavailableCheck.ok).toBe(false);
      expect(unavailableCheck.type).toBe('UNAVAILABLE');

      // Tuesday Period 0: hard blocked because absent
      const absentCheck = canAssign(sampleFaculty, sampleBatch, 0, [], initialBatches, storage.getSettings(), {
        dayOfWeek: 'Tuesday',
      });
      expect(absentCheck.ok).toBe(false);
      expect(absentCheck.type).toBe('ABSENT');
    });

    it('absence patching preserves original subject with available qualified teachers', () => {
      const initialGen = generateTimetableV2(initialBatches, initialFaculty, [], [], { seed: 112233 });
      expect(initialGen.allocations.length).toBe(372);

      // Select 5 distinct teachers to mark as absent
      const absentTeachers = Array.from(new Set(initialGen.allocations.map(a => a.facultyId))).slice(0, 5);
      const facultiesWithAbsence = initialFaculty.map(f =>
        absentTeachers.includes(f.id) ? { ...f, absentDays: ['Monday' as DayOfWeek] } : f
      );

      const patchResult = patchAbsences(initialGen.allocations, initialBatches, facultiesWithAbsence, {
        dayOfWeek: 'Monday',
        dateKey: 'Monday',
      });

      expect(patchResult.patchedCount).toBeGreaterThan(0);
      expect(patchResult.remainingGapsCount).toBe(0);

      // Verify 0 teacher overlaps after patching
      const patched = patchResult.updatedAllocations;
      for (let i = 0; i < patched.length; i++) {
        const a1 = patched[i];
        const b1 = initialBatches.find(b => b.id === a1.batchId);
        const p1 = b1?.periods[a1.periodIndex];
        if (!p1) continue;

        for (let j = i + 1; j < patched.length; j++) {
          const a2 = patched[j];
          if (a1.facultyId !== a2.facultyId) continue;
          const b2 = initialBatches.find(b => b.id === a2.batchId);
          const p2 = b2?.periods[a2.periodIndex];
          if (!p2) continue;

          expect(isOverlapping(p1.startTime, p1.endTime, p2.startTime, p2.endTime)).toBe(false);
        }
      }
    });

    it('storage fallback: gracefully retains items in memory store when localStorage throws', () => {
      const mockStorage = {
        getItem: () => null,
        setItem: () => {
          throw new Error('QuotaExceededError');
        },
        removeItem: () => {},
      };

      const originalWindow = globalThis.window;
      try {
        // @ts-expect-error Mocking window.localStorage for test
        globalThis.window = { localStorage: mockStorage };
        safeStorage.resetAvailabilityCheck();

        safeStorage.setItem('test_fallback_key', 'fallback_value');
        expect(safeStorage.getItem('test_fallback_key')).toBe('fallback_value');
      } finally {
        globalThis.window = originalWindow;
        safeStorage.resetAvailabilityCheck();
      }
    });
  });
});

